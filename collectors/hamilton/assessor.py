def parse_number(text: Optional[str]) -> Optional[float]:
    if not text:
        return None
    cleaned = re.sub(r"[^\d.]", "", text.strip())
    try:
        return float(cleaned) if cleaned else None
    except ValueError:
        return None


def parse_int(text: Optional[str]) -> Optional[int]:
    val = parse_number(text)
    return int(val) if val is not None else None


def parse_date(text: Optional[str]) -> Optional[str]:
    if not text or text.strip() in ("", "N/A", "None", "0", "00/00/0000"):
        return None
    for fmt in ("%m/%d/%Y", "%Y-%m-%d", "%m-%d-%Y", "%m/%d/%y"):
        try:
            return datetime.strptime(text.strip(), fmt).strftime("%Y-%m-%d")
        except ValueError:
            continue
    return None


def extract_lot_acres(text: str) -> Optional[float]:
    """Extract acreage from land description text like '(1.9 ACRES)' or '0.45 ACRES'."""
    if not text:
        return None
    m = re.search(r"([\d.]+)\s*ACRES?", text, re.IGNORECASE)
    if m:
        acres = float(m.group(1))
        return acres * 43560  # convert acres to sqft
    m = re.search(r"([\d,]+)\s*(?:SQ\.?\s*FT|SQUARE\s*FEET|SQFT)", text, re.IGNORECASE)
    if m:
        return float(m.group(1).replace(",", ""))
    return None


async def cell_text(row, index: int) -> str:
    """Get text of the nth div.tableLinks cell in a result row."""
    cells = row.locator("div.tableLinks")
    count = await cells.count()
    if index >= count:
        return ""
    return (await cells.nth(index).inner_text()).strip()


