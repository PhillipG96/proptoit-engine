async def enrich_existing(page: Page, conn, dry_run: bool, limit: int = 0) -> int:
    """Second-pass enrichment for all existing parcels with null lot_size_sqft."""
    enriched = 0
    select = "SELECT parcel_id, address FROM properties WHERE lot_size_sqft IS NULL ORDER BY id LIMIT %s"
    if conn is None:
        # --dry-run has no DB connection; nothing to enumerate.
        log.warning("enrich_existing: no DB connection (dry run) — nothing to enrich")
        return 0
    with conn.cursor() as cur:
        cur.execute(select, (limit or 99999,))
        rows = cur.fetchall()
    log.info("Found %d parcels needing lot_size enrichment", len(rows))

    for parcel_id, address in rows:
        extra = await enrich_from_detail(page, parcel_id)
        if extra.get("lot_size_sqft"):
            # upsert_property requires address; the old payload had only
            # parcel_id + enrichment fields, so every call returned False
            # and nothing was ever persisted despite the log saying so.
            data = {"parcel_id": parcel_id, "address": address, **extra}
            upsert_property(conn, data, dry_run=dry_run)
            enriched += 1
            log.info("  [%d] %s — %s: %d sqft", enriched, parcel_id, address, extra["lot_size_sqft"])
        await page.wait_for_timeout(500)  # small delay to avoid hitting server too hard
        if limit and enriched >= limit:
            break
    return enriched


async def _worker_scrape(page: Page, streets_batch: list[str], conn, dry_run: bool, no_enrich: bool, tab_id: int, street_idx_start: int, limit: int) -> int:
    """Worker: process a batch of streets on one tab, return count of records scraped.

    Each worker opens its OWN psycopg2 connection: psycopg2 is not safe to
    share, and the old shared conn serialized the event loop (blocking calls
    from every worker on one socket) and could interleave transactions.
    """
    worker_conn = None if dry_run else psycopg2.connect(DB_DSN)
    local_total = 0
    try:
        for idx, street in enumerate(streets_batch):
            # limit counts RECORDS written (was: street_idx_start + local_total,
            # which mixed the worker's starting street offset into a per-record
            # budget — later workers could start past the limit and write zero).
            if limit and local_total >= limit:
                break

            log.info("[Tab %d] Street %d: %s", tab_id, street_idx_start + idx + 1, street)
            records = await scrape_street(page, street)
            log.info("  Extracted %d records", len(records))

            if no_enrich:
                for rec in records:
                    if limit and local_total >= limit:
                        break
                    if upsert_property(worker_conn, rec, dry_run=dry_run):
                        local_total += 1
            else:
                for rec in records:
                    if limit and local_total >= limit:
                        break
                    extra = await enrich_from_detail(page, rec["parcel_id"])
                    if extra:
                        records_update = {k: v for k, v in extra.items() if v is not None}
                        rec.update(records_update)
                    if upsert_property(worker_conn, rec, dry_run=dry_run):
                        local_total += 1

            log.info("  Tab %d subtotal: %d records", tab_id, local_total)
    finally:
        if worker_conn is not None:
            worker_conn.close()

    return local_total


async def scrape_all(streets: list[str], limit: int, dry_run: bool, conn, enrich_existing_flag: bool = False, no_enrich: bool = False, streets_limit: int = 0, concurrency: int = 3) -> int:
    """Scrape streets using multiple browser tabs in parallel."""
    total = 0

    # Apply streets limit (0 = unlimited)
    if streets_limit > 0 and len(streets) > streets_limit:
        streets = streets[:streets_limit]
        log.info("Processing %d streets (limited from %d)", len(streets), streets_limit)

    async with async_playwright() as pw:
        browser = await pw.chromium.launch(headless=True, args=["--headless=new"])
        context = await browser.new_context(
            viewport={"width": 1280, "height": 900},
            user_agent=(
                "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
                "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
            ),
        )

        if enrich_existing_flag:
            page = await context.new_page()
            page.set_default_timeout(20000)
            total = await enrich_existing(page, conn, dry_run=dry_run, limit=limit)
        else:
            # Create worker tabs
            pages: list[Page] = []
            for i in range(concurrency):
                p = await context.new_page()
                p.set_default_timeout(20000)
                pages.append(p)
                log.info("Created tab %d/%d", i + 1, concurrency)

            # Distribute streets across tabs
            num_pages = len(pages)
            tasks = []
            for idx, page in enumerate(pages):
                start = idx * len(streets) // num_pages
                end = (idx + 1) * len(streets) // num_pages if idx < num_pages - 1 else len(streets)
                batch = streets[start:end]
                if batch:
                    # Global limit split across workers; without this each
                    # worker enforced the FULL limit and a run could write
                    # concurrency x limit records.
                    if limit:
                        base, extra = divmod(limit, num_pages)
                        worker_limit = base + (1 if idx < extra else 0)
                    else:
                        worker_limit = 0
                    tasks.append(_worker_scrape(page, batch, conn, dry_run, no_enrich, idx + 1, start, worker_limit))

            # Run all workers in parallel
            if tasks:
                results = await asyncio.gather(*tasks, return_exceptions=True)
                worker_failures = 0
                for r in results:
                    if isinstance(r, Exception):
                        worker_failures += 1
                        log.error("Worker crashed: %s", r)
                    else:
                        total += r
                if worker_failures:
                    raise RuntimeError(f"{worker_failures} scraper worker(s) failed")

            # Clean up tabs
            for p in pages:
                await p.close()

        await browser.close()

    return total


