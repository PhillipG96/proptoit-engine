async def scrape_street(page: Page, street: str) -> list[dict]:
    """Search by street name and extract all result rows directly."""
    try:
        await page.goto(BASE_URL, wait_until="networkidle", timeout=30000)
        # Blazor Server needs extra time to initialize
        await asyncio.sleep(3)

        await page.locator('input[name="SearchStreetName"]').fill(street)
        # Enter key triggers the Blazor search; clicking Go does not
        await page.locator('input[name="SearchStreetName"]').press('Enter')
        # Wait for actual results instead of fixed delay
        await page.wait_for_selector("div.trRes, .NoRecordsMessage", timeout=15000)
    except PlaywrightTimeout:
        FAILED_STREETS.add(street)
        log.warning("Timeout loading search page for '%s'", street)
        return []

    # Check if "No Results" message appeared
    try:
        no_records = await page.locator(".NoRecordsMessage").count()
        if no_records > 0:
            log.info("  No results for '%s'", street)
            return []
    except Exception:
        pass

    records = []
    page_num = 0

    while True:
        page_num += 1
        rows = page.locator("div.trRes")
        count = await rows.count()
        log.info("  Page %d: %d rows", page_num, count)

        if count == 0:
            break

        for i in range(count):
            row = rows.nth(i)
            try:
                parcel_id  = await cell_text(row, 0)
                address    = await cell_text(row, 1)
                owner      = await cell_text(row, 2)
                year_built = await cell_text(row, 3)
                assessed   = await cell_text(row, 4)
                bldg_sqft  = await cell_text(row, 5)
                sale_date  = await cell_text(row, 7)
                sale_price = await cell_text(row, 8)

                if not parcel_id or not address:
                    continue

                # Derive postal code from known Chattanooga context
                postal_code = "37401"
                m = re.search(r"\b(3[67]\d{3})\b", address)
                if m:
                    postal_code = m.group(1)

                records.append({
                    "parcel_id":           parcel_id,
                    "address":             address,
                    "city":                "Chattanooga",
                    "state":               "TN",
                    "postal_code":         postal_code,
                    "owner_of_record":     owner or None,
                    "owner_mailing_address": None,
                    "owner_occupant":      False,
                    "assessed_value":      parse_number(assessed),
                    "year_built":          parse_int(year_built),
                    "building_sqft":       parse_number(bldg_sqft),
                    "lot_size_sqft":       None,  # filled by enrich_from_detail
                    "bedrooms":            None,
                    "bathrooms":           None,
                    "last_sale_price":     parse_number(sale_price),
                    "last_sale_date":      parse_date(sale_date),
                })
            except Exception as exc:
                log.debug("Row %d parse error: %s", i, exc)

        # Check for next-page button
        next_btn = page.locator("button:has-text('Next'), a:has-text('Next'), [aria-label='Next']").first
        try:
            if await next_btn.count() > 0 and await next_btn.is_enabled():
                # Snapshot the first cell so we can detect an ACTUAL page
                # change. wait_for_selector("div.trRes") resolves immediately
                # because the previous page's rows are still in the DOM, so
                # it used to re-scrape (and duplicate-append) the same page.
                first_cell_before = await cell_text(page.locator("div.trRes").first, 0)
                await next_btn.click()
                await page.wait_for_function(
                    """(prevFirst) => {
                        // Compare the SAME element cell_text(row,0) extracts
                        // (first tableLinks cell = parcel id). Comparing
                        // div.trRes.innerText (whole row incl. address) against
                        // a parcel-id snapshot never matched reliably.
                        const c = document.querySelector('div.trRes div.tableLinks');
                        return c && c.innerText.trim().slice(0, 20) !== prevFirst;
                    }""",
                    arg=first_cell_before[:20],
                    timeout=10000,
                )
            else:
                break
        except Exception:
            break

    return records


