def main() -> None:
    parser = argparse.ArgumentParser(description="Hamilton County Assessor scraper")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--limit", type=int, default=0,
                        help="Max records to upsert (default: unlimited)")
    parser.add_argument("--streets", type=str, default="")
    parser.add_argument("--streets-limit", type=int, default=0,
                        help="Max streets to process (default: all)")
    parser.add_argument("--enrich-existing", action="store_true",
                        help="Second-pass: scrape detail pages for existing parcels with null lot_size")
    parser.add_argument("--no-enrich", action="store_true",
                        help="Skip enrichment (lot_size, mailing addr) — fast first pass only")
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s  %(levelname)-7s  %(message)s",
        stream=sys.stdout,
    )

    # Load streets from filtered file (~6.5k streets) or use --streets arg
    _script_dir = os.path.dirname(os.path.abspath(__file__))
    _streets_file = os.path.join(_script_dir, "..", "..", "data", "streets_filtered.json")
    if args.streets:
        streets = [s.strip().upper() for s in args.streets.split(",") if s.strip()]
    else:
        try:
            with open(_streets_file) as f:
                _data = json.load(f)
            streets = [s.upper() for s in _data.get("streets", [])]
        except FileNotFoundError:
            log.warning("Streets file not found, falling back to hardcoded list")
            streets = DEFAULT_STREETS
    log.info("Streets to scan: %d", len(streets))

    conn = None
    if not args.dry_run:
        try:
            conn = psycopg2.connect(DB_DSN)
            log.info("Connected to Postgres")
        except Exception as exc:
            log.error("Cannot connect to Postgres: %s", exc)
            sys.exit(1)

    try:
        if args.enrich_existing:
            # Second-pass enrichment mode
            total = asyncio.run(scrape_all(streets, args.limit, args.dry_run, conn, enrich_existing_flag=True, streets_limit=args.streets_limit))
            log.info("Done. Records enriched: %d", total)
        else:
            total = asyncio.run(scrape_all(streets, args.limit, args.dry_run, conn, no_enrich=args.no_enrich, streets_limit=args.streets_limit))
            if args.no_enrich:
                log.info("Done. Records written (fast, no enrichment): %d", total)
            else:
                log.info("Done. Records written: %d", total)
            if FAILED_STREETS:
                log.warning("Timed out %d street(s): %s", len(FAILED_STREETS), ", ".join(sorted(FAILED_STREETS)))
                # Don't fail the whole batch for a few slow streets — partial results are still valuable
    finally:
        if conn:
            conn.close()


if __name__ == "__main__":
    main()
