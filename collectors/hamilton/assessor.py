UPSERT_SQL = """
    INSERT INTO properties (
        county_id, parcel_id, address, city, state, postal_code,
        owner_of_record, owner_mailing_address, owner_occupant,
        assessed_value, year_built, building_sqft, lot_size_sqft, bedrooms, bathrooms,
        last_sale_price, last_sale_date, updated_at
    ) VALUES (
        'hamilton', %(parcel_id)s, %(address)s, %(city)s, %(state)s, %(postal_code)s,
        %(owner_of_record)s, %(owner_mailing_address)s, %(owner_occupant)s,
        %(assessed_value)s, %(year_built)s, %(building_sqft)s, %(lot_size_sqft)s,
        %(bedrooms)s, %(bathrooms)s,
        %(last_sale_price)s, %(last_sale_date)s,
        NOW()
    )
    ON CONFLICT (county_id, parcel_id) DO UPDATE SET
        address               = EXCLUDED.address,
        owner_of_record       = EXCLUDED.owner_of_record,
        assessed_value        = COALESCE(EXCLUDED.assessed_value, properties.assessed_value),
        year_built            = COALESCE(EXCLUDED.year_built, properties.year_built),
        building_sqft         = COALESCE(EXCLUDED.building_sqft, properties.building_sqft),
        lot_size_sqft         = COALESCE(EXCLUDED.lot_size_sqft, properties.lot_size_sqft),
        last_sale_price       = COALESCE(EXCLUDED.last_sale_price, properties.last_sale_price),
        last_sale_date        = COALESCE(EXCLUDED.last_sale_date, properties.last_sale_date),
        -- preserve mailing address if already enriched; only overwrite if we have a new value
        owner_mailing_address = COALESCE(EXCLUDED.owner_mailing_address, properties.owner_mailing_address),
        owner_occupant        = CASE WHEN EXCLUDED.owner_mailing_address IS NOT NULL
                                     THEN EXCLUDED.owner_occupant
                                     ELSE properties.owner_occupant END,
        updated_at            = NOW()
"""


def upsert_property(conn, data: dict, dry_run: bool = False) -> bool:
    if not data.get("parcel_id") or not data.get("address"):
        return False

    row = {
        "parcel_id":            str(data["parcel_id"]).strip(),
        "address":              str(data["address"]).strip(),
        "city":                 data.get("city", "Chattanooga"),
        "state":                data.get("state", "TN"),
        "postal_code":          data.get("postal_code") or "37401",
        "owner_of_record":      data.get("owner_of_record"),
        "owner_mailing_address": data.get("owner_mailing_address"),
        "owner_occupant":       bool(data.get("owner_occupant", False)),
        "assessed_value":       data.get("assessed_value"),
        "year_built":           data.get("year_built"),
        "building_sqft":        data.get("building_sqft"),
        "lot_size_sqft":        data.get("lot_size_sqft"),
        "bedrooms":             data.get("bedrooms"),
        "bathrooms":            data.get("bathrooms"),
        "last_sale_price":      data.get("last_sale_price"),
        "last_sale_date":       data.get("last_sale_date"),
    }

    if dry_run:
        log.info("[DRY] %s — %s  assessed=$%s", row["parcel_id"], row["address"],
                 row["assessed_value"] or "?")
        return True

    with conn.cursor() as cur:
        cur.execute(UPSERT_SQL, row)
    conn.commit()
    return True


