async def enrich_from_detail(page: Page, parcel_id: str) -> dict:
    """Visit the detail page for a parcel and extract lot_size_sqft and owner mailing address."""
    import urllib.parse
    try:
        encoded_id = urllib.parse.quote(parcel_id)
        await page.goto(f"https://assessor.hamiltontn.gov/card/{encoded_id}", wait_until="networkidle", timeout=15000)
        await asyncio.sleep(2)
        body = await page.locator("body").inner_text()

        # Check if page returned "Not Found"
        if "Not Found" in body:
            return {}

        result: dict = {}
        # Lot size from Land Description section.
        # The old pattern ([^\n]*(?:\n[^\n]*)*) had no terminator and
        # swallowed everything to end-of-page, so extract_lot_acres could
        # grab a number from an unrelated section. Stop at the next known
        # section header (or at most a few lines).
        lot_text_match = re.search(
            r"Land Description\s*\n((?:(?!\s*(?:Current Property|Owner|Mailing|Sales|Assessed)\b)[^\n]*(?:\n|$)){0,8})",
            body, re.IGNORECASE)
        if lot_text_match:
            land_desc = lot_text_match.group(1)
            acres = extract_lot_acres(land_desc)
            if acres:
                result["lot_size_sqft"] = acres
        
        # Owner mailing address: between 'Current Property Mailing Address' and 'Current Property Sales'
        addr_match = re.search(r"Current Property Mailing Address\s*\n((?:(?!\nCurrent Property Sales)\n?[^\n]*)*)", body)
        if addr_match:
            raw = addr_match.group(1).strip()
            lines = [l.strip().lstrip('\t ') for l in raw.split('\n') if l.strip() and not l.strip().startswith('\t')]
            # Filter out labels
            lines = [l for l in lines if l and l not in ('Owner', 'City', 'State', 'Address', 'Zip', '')]
            if len(lines) >= 3:
                addr_parts = " ".join(lines)
                # Clean up multiple spaces
                addr_parts = re.sub(r'\s+', ' ', addr_parts).strip()
                result["owner_mailing_address"] = addr_parts
                result["owner_occupant"] = False
        
        return result
    except Exception as exc:
        log.debug("Detail enrichment failed for %s: %s", parcel_id, exc)
        return {}


