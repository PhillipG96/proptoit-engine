"""Offline Ed25519 license verification for PropToIt Pro — fail-closed.

Contract (Task 2.1):

    verify(key_str) -> KeyInfo

  * checks the Ed25519 signature against the public key embedded below,
  * checks the engine version pin (``major_version`` must equal
    ``ENGINE_MAJOR_VERSION``) and the tier,
  * makes NO network calls — verification is fully local/offline.

Fail-closed: every tampered, expired, malformed or wrong-key input returns
``KeyInfo(valid=False, reason=...)``. ``verify()`` never raises and never
returns anything but a ``KeyInfo``. Callers gate on ``info.valid``.

License wire format (v1)::

    PTOIT1.<base64url(canonical payload JSON)>.<base64url(64-byte signature)>

Canonical payload JSON is ``json.dumps(payload, sort_keys=True,
separators=(",", ":"), ensure_ascii=True).encode("utf-8")`` — the exact
serialization ``scripts/license_keygen.py`` signs.

Payload fields: ``tier`` ("personal" | "platform"), ``email`` (str),
``major_version`` (int, pinned to this engine's major version), and optional
``exp`` (ISO date ``YYYY-MM-DD``; the license is valid through the end of
that day).

Crypto: the ``cryptography`` package — chosen over pynacl because it is
already present in the runtime environment (no new dependency) and provides
raw Ed25519 sign/verify in one stable import. Declared in requirements.txt.

Key rotation: regenerate a keypair with ``scripts/license_keygen.py`` and
replace ``_ED25519_PUB_HEX`` below. The public key is PUBLIC (it verifies,
it cannot sign) and is safe to commit. The private key never leaves the
machine (default ``~/.hermes/secrets/proptoit-engine/license_ed25519.key``,
gitignored) and must NEVER be committed.
"""

from __future__ import annotations

import base64
import binascii
import json
import re
from dataclasses import dataclass
from datetime import date

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

LICENSE_PREFIX = "PTOIT1"
LICENSE_TIERS = frozenset({"personal", "platform"})

# Engine major version this license release is pinned to. Keep in sync with
# the engine version reported by api/app.py (currently 0.1.0). A license
# signed for any other major is rejected (version pin).
ENGINE_MAJOR_VERSION = 0

# Ed25519 PUBLIC key (safe to commit — it verifies signatures, it cannot
# create them). Generated by scripts/license_keygen.py; the private
# counterpart lives OUTSIDE the repo in
# ~/.hermes/secrets/proptoit-engine/license_ed25519.key (gitignored).
_ED25519_PUB_HEX = (
    "30c92c507d36a26ed5110f8795ddddd501a666973ca90b06daeaa82ef6a124d0"
)

_REQUIRED_FIELDS = frozenset({"tier", "email", "major_version"})
_OPTIONAL_FIELDS = frozenset({"exp"})
_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


@dataclass(frozen=True)
class KeyInfo:
    """Result of ``verify()``. ``valid`` is the only field callers gate on."""

    valid: bool = False
    tier: str = ""
    email: str = ""
    major_version: int = -1
    exp: str = ""  # ISO date the license expires (end of day), "" if none
    reason: str = "not verified"


class _Reject(Exception):
    """Internal control flow: a precise, fail-closed rejection reason."""

    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


def b64url_encode(raw: bytes) -> str:
    """Unpadded base64url."""
    return base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")


def b64url_decode(text: str) -> bytes:
    """Strict base64url: padding-tolerant, alphabet-validated."""
    return base64.b64decode(text + "=" * (-len(text) % 4), altchars=b"-_", validate=True)


def canonical_payload_bytes(payload: dict) -> bytes:
    """Deterministic JSON serialization shared by signer and verifier."""
    return json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("utf-8")


def pack_license(payload_bytes: bytes, signature: bytes) -> str:
    """Assemble the wire-format license string."""
    return ".".join((LICENSE_PREFIX, b64url_encode(payload_bytes), b64url_encode(signature)))


def verify(key_str: str) -> KeyInfo:
    """Verify an offline license key string.

    Fail-closed: returns ``KeyInfo(valid=False, reason=...)`` for every
    invalid input and never raises, so a bug can never become an allowance.
    """
    try:
        return _verify(key_str)
    except _Reject as rej:
        return KeyInfo(valid=False, reason=rej.reason)
    except Exception as exc:  # noqa: BLE001 — absolute fail-closed backstop
        return KeyInfo(valid=False, reason=f"invalid license ({type(exc).__name__})")


def _verify(key_str: str) -> KeyInfo:
    if not isinstance(key_str, str) or not key_str.strip():
        raise _Reject("empty license")

    parts = key_str.strip().split(".")
    if len(parts) != 3 or parts[0] != LICENSE_PREFIX:
        raise _Reject(f"malformed license: expected {LICENSE_PREFIX}.<payload>.<signature>")

    try:
        payload = b64url_decode(parts[1])
        signature = b64url_decode(parts[2])
    except (ValueError, binascii.Error):
        raise _Reject("malformed license: payload/signature is not valid base64url") from None
    if len(signature) != 64:
        raise _Reject(f"malformed license: signature must be 64 bytes, got {len(signature)}")

    try:
        data = json.loads(payload)
    except (ValueError, UnicodeDecodeError):
        raise _Reject("malformed license: payload is not valid JSON") from None
    if not isinstance(data, dict):
        raise _Reject("malformed license: payload must be a JSON object")

    keys = set(data)
    missing = _REQUIRED_FIELDS - keys
    unknown = keys - _REQUIRED_FIELDS - _OPTIONAL_FIELDS
    if missing:
        raise _Reject(f"license is missing required field(s): {sorted(missing)}")
    if unknown:
        raise _Reject(f"license has unknown field(s): {sorted(unknown)}")

    tier = data["tier"]
    if not isinstance(tier, str) or tier not in LICENSE_TIERS:
        raise _Reject(f"license tier must be one of {sorted(LICENSE_TIERS)}")

    email = data["email"]
    if not isinstance(email, str) or not 3 <= len(email) <= 254 or "@" not in email:
        raise _Reject("license email is missing or invalid")

    major_version = data["major_version"]
    if isinstance(major_version, bool) or not isinstance(major_version, int):
        raise _Reject("license major_version must be an integer")
    if major_version != ENGINE_MAJOR_VERSION:
        raise _Reject(
            f"license is for engine major version {major_version}; this engine is "
            f"major version {ENGINE_MAJOR_VERSION} (version pin)"
        )

    exp = ""
    if "exp" in data:
        raw_exp = data["exp"]
        if not isinstance(raw_exp, str) or not _DATE_RE.match(raw_exp):
            raise _Reject("license exp must be an ISO date (YYYY-MM-DD)")
        try:
            exp_date = date.fromisoformat(raw_exp)
        except ValueError:
            raise _Reject("license exp is not a valid date") from None
        if date.today() > exp_date:
            raise _Reject(f"license expired on {raw_exp}")
        exp = raw_exp

    # Signature is proven over the exact canonical payload bytes, against the
    # embedded public key, derived per call (so a bad constant fails closed
    # rather than at import). Nothing above is trusted until this passes.
    try:
        pubkey = Ed25519PublicKey.from_public_bytes(bytes.fromhex(_ED25519_PUB_HEX))
    except (ValueError, TypeError) as exc:
        raise _Reject(f"verifier misconfigured: embedded public key is invalid ({exc})") from None
    try:
        pubkey.verify(signature, payload)
    except InvalidSignature:
        raise _Reject("invalid signature") from None

    return KeyInfo(
        valid=True, tier=tier, email=email, major_version=major_version, exp=exp, reason="ok"
    )
